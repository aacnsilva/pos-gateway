import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { z } from 'zod';
import { fieldEnd, LAYOUT } from '../src/ingestion/adapters/fixed-width.layout';
import { jsonSaleV1 } from '../src/ingestion/adapters/json-till.schema';

/**
 * Format docs generated from code are never hand-edited. These tests fail when the docs
 * drift from the code; `npm run docs:sync` regenerates them.
 */
const update = process.env.UPDATE_DOCS === '1';
const docsPath = (name: string) => join(__dirname, '../docs/formats', name);

function expectInSync(path: string, generated: string): void {
  if (update) writeFileSync(path, generated);
  expect(readFileSync(path, 'utf8')).toBe(generated);
}

describe('generated format docs', () => {
  it('json-sale-v1.schema.json matches the zod wire schema', () => {
    const schema = {
      ...z.toJSONSchema(jsonSaleV1),
      title: 'POS sale (JSON till), schema version 1',
    };
    expectInSync(docsPath('json-sale-v1.schema.json'), `${JSON.stringify(schema, null, 2)}\n`);
  });

  it('fixed-width.md layout tables match the parser layout', () => {
    const path = docsPath('fixed-width.md');
    const start = '<!-- layout:start (generated by npm run docs:sync) -->';
    const end = '<!-- layout:end -->';
    const tables = Object.values(LAYOUT)
      .map((spec) =>
        [
          `### \`${spec.type}\` – ${spec.title}`,
          '',
          '| Columns | Length | Field | Kind | Description |',
          '| --- | --- | --- | --- | --- |',
          ...spec.fields.map(
            (f) =>
              `| ${f.length === 1 ? f.start : `${f.start}–${fieldEnd(f)}`} | ${f.length} | \`${f.name}\` | ${f.kind} | ${f.description} |`,
          ),
        ].join('\n'),
      )
      .join('\n\n');

    const current = readFileSync(path, 'utf8');
    const before = current.slice(0, current.indexOf(start) + start.length);
    const after = current.slice(current.indexOf(end));
    expect(current.includes(start) && current.includes(end)).toBe(true);
    expectInSync(path, `${before}\n\n${tables}\n\n${after}`);
  });
});
